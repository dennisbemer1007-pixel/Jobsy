def emit_lang_method(lang: str, method: str) -> str:
    lines = ['        new(StringComparer.OrdinalIgnoreCase)', "        {"]
    for prefix, stems in (
        ("Values", values_stems(lang)),
        ("Career", career_stems(lang)),
        ("Culture", culture_fixes(lang)),
    ):
        for q, text in sorted(stems.items(), key=lambda x: int(x[0][1:])):
            key = f"AssessmentV2.{prefix}.{q}"
            esc = text.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'            ["{key}"] = "{esc}",')
    lines.append("        };")
    return f"    private static Dictionary<string, string> {method}() =>\n" + "\n".join(lines)



    private static readonly Dictionary<string, Dictionary<string, string>> Catalog = Build();

    public static string Get(string key, string? language = null)
    {
        var lang = JobsyLanguages.Normalize(language);
        if (Catalog.TryGetValue(lang, out var map) && map.TryGetValue(key, out var value))
        {
            return value;
        }

        if (lang != JobsyLanguages.Default
            && Catalog[JobsyLanguages.Default].TryGetValue(key, out var fallback))
        {
            return fallback;
        }

        return key;
    }


COMP_NAMES = list(UITGEBREID_COMPETENCES)
assert set(COMPETENTIE_ITEMS) == set(COMP_NAMES)
assert {c[3] for c in CHECKS} <= set(COMP_NAMES)


def _flip(idx: int) -> bool:
    return idx % 2 == 1


def _interesse_items() -> list[Item]:
    items: list[Item] = []
    n = 0
    for k in range(30):
        for (first, second), rows in RIASEC_PAREN.items():
            sector, sit, o1, o2 = rows[k]
            d1, d2 = RIASEC[first], RIASEC[second]
            if _flip(k):
                o1, o2, d1, d2 = o2, o1, d2, d1
            display = 1 if n < 45 else 2
            n += 1
            items.append(Item("interesse", display, "ab", sit, KOP_AB, o1, d1, o2, d2, sector))
    return items


def _competentie_items() -> list[Item]:
    ab: list[Item] = []
    for k in range(6):
        for comp in COMP_NAMES:
            sector, sit, hoog, laag = COMPETENTIE_ITEMS[comp][k]
            ab.append(Item("competentie", 3, "ab", sit, KOP_AB, hoog, comp, laag, comp, sector))

    items: list[Item] = []
    checks = iter(CHECKS)
    for i, it in enumerate(ab):
        it.display_blok = 3 if i < 36 else 4
        items.append(it)
        if (i + 1) % 9 == 0:
            c_sector, c_sit, stelling, comp = next(checks)
            items.append(
                Item("competentie", it.display_blok, "check", c_sit, KOP_CHECK, stelling, comp, "", "", c_sector)
            )
    return items


def _werkwaarden_items() -> list[Item]:
    items: list[Item] = []
    n = 0
    for k in range(10):
        for (first, second), rows in WERKWAARDE_PAREN.items():
            sector, sit, o1, o2 = rows[k]
            d1, d2 = SCHWARTZ[first], SCHWARTZ[second]
            if _flip(k):
                o1, o2, d1, d2 = o2, o1, d2, d1
            display = 5 if n < 15 else 6
            n += 1
            items.append(Item("werkwaarden", display, "ab", sit, KOP_AB, o1, d1, o2, d2, sector))
    return items


def load_uitgebreid_items() -> list[Item]:
    return _interesse_items() + _competentie_items() + _werkwaarden_items()


